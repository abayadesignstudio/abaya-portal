/// An icon drawn like the web app's: round line ends, 2-point lines on a 24-point grid, or filled.
struct GlyphView: View {
    let n: String
    var s: CGFloat = 24
    var w: CGFloat = 2
    var fill = false
    var body: some View {
        let scaled = Glyph.path(n).applying(CGAffineTransform(scaleX: s / 24, y: s / 24))
        ZStack {
            if fill || n == "feed" { scaled.fill() }
            scaled.stroke(style: StrokeStyle(lineWidth: (n == "feed" ? 1.2 : w) * s / 24, lineCap: .round, lineJoin: .round))
        }
        .frame(width: s, height: s)
    }
}
